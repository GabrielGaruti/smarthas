PROMPT ===== [1/4] Migracao de schema (idempotente) =====
DECLARE
  v_existe NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_existe FROM user_tables WHERE table_name = 'T_SHAS_AUDITORIA_ALERTA';
  IF v_existe = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE T_SHAS_AUDITORIA_ALERTA (
        ID_AUDITORIA     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
        ID_ALERTA        NUMBER        NOT NULL,
        ID_USUARIO       NUMBER        NOT NULL,
        TP_OPERACAO      VARCHAR2(10)  NOT NULL,
        ST_ANTERIOR      VARCHAR2(10),
        ST_NOVO          VARCHAR2(10),
        NV_SEVERIDADE    VARCHAR2(10),
        NM_USUARIO_BD    VARCHAR2(128) DEFAULT USER NOT NULL,
        DS_ORIGEM        VARCHAR2(200),
        DT_OPERACAO      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT PK_SHAS_AUDITORIA_ALERTA PRIMARY KEY (ID_AUDITORIA),
        CONSTRAINT CK_SHAS_AUDITORIA_OPER   CHECK (TP_OPERACAO IN ('INSERT','UPDATE','DELETE'))
      )]';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_SHAS_AUDITORIA_ALERTA ON T_SHAS_AUDITORIA_ALERTA (ID_ALERTA, DT_OPERACAO)';
    DBMS_OUTPUT.PUT_LINE('T_SHAS_AUDITORIA_ALERTA criada.');
  ELSE
    DBMS_OUTPUT.PUT_LINE('T_SHAS_AUDITORIA_ALERTA ja existe.');
  END IF;
END;
/

PROMPT ===== [2/4] Removendo objetos avulsos da Fase 6 =====
BEGIN
  FOR o IN (SELECT object_name, object_type FROM user_objects
             WHERE object_type IN ('PROCEDURE','FUNCTION')
               AND (object_name LIKE 'PRC\_SHAS\_%' ESCAPE '\' OR object_name LIKE 'FN\_SHAS\_%' ESCAPE '\')) LOOP
    EXECUTE IMMEDIATE 'DROP ' || o.object_type || ' ' || o.object_name;
    DBMS_OUTPUT.PUT_LINE('Removido: ' || o.object_type || ' ' || o.object_name);
  END LOOP;
END;
