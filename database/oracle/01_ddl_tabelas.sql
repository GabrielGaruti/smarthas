-- ============================================================
-- Smart HAS - Fase 6 | 01_ddl_tabelas.sql
-- Modelo fisico Oracle (19c+). Convencoes FIAP:
--   T_  = tabela | PK_/FK_/UK_/CK_/IX_ = constraints e indices
--   ID_ = identificador | NM_ = nome | DS_ = descricao | DT_ = data
--   VL_ = valor | QT_ = quantidade | PC_ = percentual | TP_ = tipo
--   ST_ = status | NV_ = nivel | CD_ = codigo
-- As chaves usam IDENTITY (compativel com GenerationType.IDENTITY do JPA).
-- ============================================================

-- 1) Usuarios (pacientes e administradores)
CREATE TABLE T_SHAS_USUARIO (
  ID_USUARIO     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NM_COMPLETO    VARCHAR2(120) NOT NULL,
  DS_EMAIL       VARCHAR2(150) NOT NULL,
  DS_SENHA_HASH  VARCHAR2(100) NOT NULL,          -- BCrypt (nunca senha em texto)
  TP_PERFIL      VARCHAR2(10)  DEFAULT 'USER' NOT NULL,
  DT_CADASTRO    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SHAS_USUARIO        PRIMARY KEY (ID_USUARIO),
  CONSTRAINT UK_SHAS_USUARIO_EMAIL  UNIQUE (DS_EMAIL),
  CONSTRAINT CK_SHAS_USUARIO_PERFIL CHECK (TP_PERFIL IN ('USER','ADMIN'))
);

-- 2) Unidades de saude / pontos do mapa (AI Logistics Extension)
CREATE TABLE T_SHAS_UNIDADE_SAUDE (
  ID_UNIDADE     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NM_UNIDADE     VARCHAR2(120) NOT NULL,
  TP_UNIDADE     VARCHAR2(10)  NOT NULL,
  VL_LATITUDE    NUMBER(9,6)   NOT NULL,
  VL_LONGITUDE   NUMBER(9,6)   NOT NULL,
  DS_ENDERECO    VARCHAR2(200),
  ST_ATIVO       NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT PK_SHAS_UNIDADE       PRIMARY KEY (ID_UNIDADE),
  CONSTRAINT CK_SHAS_UNIDADE_TIPO  CHECK (TP_UNIDADE IN ('HOSPITAL','CLINIC','SENSOR')),
  CONSTRAINT CK_SHAS_UNIDADE_ATIVO CHECK (ST_ATIVO IN (0,1))
);

-- 3) Dispositivos IoT (monitores de pressao conectados) vinculados ao paciente
CREATE TABLE T_SHAS_DISPOSITIVO (
  ID_DISPOSITIVO  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_USUARIO      NUMBER        NOT NULL,
  CD_SERIE        VARCHAR2(40)  NOT NULL,
  DS_MODELO       VARCHAR2(80)  NOT NULL,
  ST_ATIVO        NUMBER(1)     DEFAULT 1 NOT NULL,
  DT_ULTIMA_SYNC  TIMESTAMP,
  CONSTRAINT PK_SHAS_DISPOSITIVO        PRIMARY KEY (ID_DISPOSITIVO),
  CONSTRAINT UK_SHAS_DISPOSITIVO_SERIE  UNIQUE (CD_SERIE),
  CONSTRAINT FK_SHAS_DISPOSITIVO_USU    FOREIGN KEY (ID_USUARIO) REFERENCES T_SHAS_USUARIO (ID_USUARIO),
  CONSTRAINT CK_SHAS_DISPOSITIVO_ATIVO  CHECK (ST_ATIVO IN (0,1))
);

-- 4) Medicoes de pressao arterial (manuais ou vindas de sensor)
CREATE TABLE T_SHAS_MEDICAO (
  ID_MEDICAO        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_USUARIO        NUMBER        NOT NULL,
  ID_DISPOSITIVO    NUMBER,                        -- NULL quando registrada manualmente
  VL_SISTOLICA      NUMBER(3)     NOT NULL,
  VL_DIASTOLICA     NUMBER(3)     NOT NULL,
  VL_FREQ_CARDIACA  NUMBER(3),
  DT_MEDICAO        TIMESTAMP     NOT NULL,        -- momento em que a pressao foi aferida
  TP_ORIGEM         VARCHAR2(10)  DEFAULT 'MANUAL' NOT NULL,
  DS_OBSERVACAO     VARCHAR2(500),
  DT_REGISTRO       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SHAS_MEDICAO          PRIMARY KEY (ID_MEDICAO),
  CONSTRAINT FK_SHAS_MEDICAO_USU      FOREIGN KEY (ID_USUARIO)     REFERENCES T_SHAS_USUARIO (ID_USUARIO),
  CONSTRAINT FK_SHAS_MEDICAO_DISP     FOREIGN KEY (ID_DISPOSITIVO) REFERENCES T_SHAS_DISPOSITIVO (ID_DISPOSITIVO),
  CONSTRAINT CK_SHAS_MEDICAO_SIS      CHECK (VL_SISTOLICA  BETWEEN 50 AND 300),
  CONSTRAINT CK_SHAS_MEDICAO_DIA      CHECK (VL_DIASTOLICA BETWEEN 30 AND 200),
  CONSTRAINT CK_SHAS_MEDICAO_FC       CHECK (VL_FREQ_CARDIACA IS NULL OR VL_FREQ_CARDIACA BETWEEN 30 AND 220),
  CONSTRAINT CK_SHAS_MEDICAO_ORIGEM   CHECK (TP_ORIGEM IN ('MANUAL','SENSOR'))
);
CREATE INDEX IX_SHAS_MEDICAO_USU_DATA ON T_SHAS_MEDICAO (ID_USUARIO, DT_MEDICAO);

-- 5) Alertas clinicos gerados pela procedure PRC_SHAS_REGISTRAR_ALERTA
CREATE TABLE T_SHAS_ALERTA (
  ID_ALERTA       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_USUARIO      NUMBER        NOT NULL,
  ID_MEDICAO      NUMBER        NOT NULL,
  TP_ALERTA       VARCHAR2(30)  NOT NULL,
  NV_SEVERIDADE   VARCHAR2(10)  NOT NULL,
  DS_MENSAGEM     VARCHAR2(400) NOT NULL,
  ST_ALERTA       VARCHAR2(10)  DEFAULT 'ABERTO' NOT NULL,
  DT_ALERTA       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  DT_RESOLUCAO    TIMESTAMP,
  CONSTRAINT PK_SHAS_ALERTA          PRIMARY KEY (ID_ALERTA),
  CONSTRAINT FK_SHAS_ALERTA_USU      FOREIGN KEY (ID_USUARIO) REFERENCES T_SHAS_USUARIO (ID_USUARIO),
  CONSTRAINT FK_SHAS_ALERTA_MED      FOREIGN KEY (ID_MEDICAO) REFERENCES T_SHAS_MEDICAO (ID_MEDICAO) ON DELETE CASCADE,
  CONSTRAINT UK_SHAS_ALERTA_MED_TIPO UNIQUE (ID_MEDICAO, TP_ALERTA),   -- idempotencia
  CONSTRAINT CK_SHAS_ALERTA_TIPO     CHECK (TP_ALERTA IN ('CRISE_HIPERTENSIVA','HIPERTENSAO','TENDENCIA_ALTA')),
  CONSTRAINT CK_SHAS_ALERTA_SEV      CHECK (NV_SEVERIDADE IN ('MODERADO','ALTO','CRITICO')),
  CONSTRAINT CK_SHAS_ALERTA_STATUS   CHECK (ST_ALERTA IN ('ABERTO','RESOLVIDO'))
);
CREATE INDEX IX_SHAS_ALERTA_USU_ST ON T_SHAS_ALERTA (ID_USUARIO, ST_ALERTA);

-- 6) Relatorios resumidos por paciente (PRC_SHAS_GERAR_RELATORIO_RESUMO)
CREATE TABLE T_SHAS_RELATORIO_RESUMO (
  ID_RELATORIO         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_USUARIO           NUMBER        NOT NULL,
  DT_INICIO            DATE          NOT NULL,
  DT_FIM               DATE          NOT NULL,
  QT_MEDICOES          NUMBER(6)     NOT NULL,
  VL_MEDIA_SISTOLICA   NUMBER(5,1),
  VL_MEDIA_DIASTOLICA  NUMBER(5,1),
  VL_MAX_SISTOLICA     NUMBER(3),
  PC_CONTROLE          NUMBER(5,1),
  QT_ALERTAS_ABERTOS   NUMBER(6)     NOT NULL,
  NV_RISCO             VARCHAR2(10)  NOT NULL,
  DS_RESUMO            VARCHAR2(400),
  DT_GERACAO           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SHAS_RELATORIO      PRIMARY KEY (ID_RELATORIO),
  CONSTRAINT FK_SHAS_RELATORIO_USU  FOREIGN KEY (ID_USUARIO) REFERENCES T_SHAS_USUARIO (ID_USUARIO),
  CONSTRAINT CK_SHAS_RELATORIO_RISCO CHECK (NV_RISCO IN ('SEM DADOS','BAIXO','MODERADO','ALTO'))
);

-- 7) Log de processamento das rotinas PL/SQL (governanca / auditoria)
CREATE TABLE T_SHAS_LOG_PROCESSAMENTO (
  ID_LOG       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NM_ROTINA    VARCHAR2(60)   NOT NULL,
  TP_EVENTO    VARCHAR2(10)   NOT NULL,
  DS_MENSAGEM  VARCHAR2(4000),
  DT_LOG       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SHAS_LOG        PRIMARY KEY (ID_LOG),
  CONSTRAINT CK_SHAS_LOG_EVENTO CHECK (TP_EVENTO IN ('INFO','AVISO','ERRO'))
);

COMMENT ON TABLE T_SHAS_USUARIO           IS 'Pacientes e administradores do Smart HAS';
COMMENT ON TABLE T_SHAS_UNIDADE_SAUDE     IS 'Hospitais, UBS e sensores publicos exibidos no mapa';
COMMENT ON TABLE T_SHAS_DISPOSITIVO       IS 'Monitores de pressao IoT vinculados a um paciente';
COMMENT ON TABLE T_SHAS_MEDICAO           IS 'Leituras de pressao arterial (manuais ou de sensor)';
COMMENT ON TABLE T_SHAS_ALERTA            IS 'Alertas clinicos gerados por PRC_SHAS_REGISTRAR_ALERTA';
COMMENT ON TABLE T_SHAS_RELATORIO_RESUMO  IS 'Relatorios gerados por PRC_SHAS_GERAR_RELATORIO_RESUMO';
COMMENT ON TABLE T_SHAS_LOG_PROCESSAMENTO IS 'Auditoria das rotinas PL/SQL';
